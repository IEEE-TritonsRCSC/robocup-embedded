void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan) {
	//HAL_GPIO_TogglePin(LED_GREEN_PORT,LED_GREEN_PIN);
	if (hcan == &hcan1) {
		HAL_CAN_GetRxMessage(&hcan1, CAN_RX_FIFO0, &canRxHeader, CAN_RxData);

		if (canRxHeader.StdId == 0x201)
			motor_idx = 0;
		if (canRxHeader.StdId == 0x202)
			motor_idx = 1;
		if (canRxHeader.StdId == 0x203)
			motor_idx = 2;
		if (canRxHeader.StdId == 0x204)
			motor_idx = 3;

		// angle of the motor (0 - 8191 corresponding with 0 - 360°)
		angle_data[motor_idx] = (uint16_t) (CAN_RxData[0] << 8 | CAN_RxData[1]);

		// speed of the motor in rpm
		int16_t rpm = (int16_t)((CAN_RxData[2] << 8) | CAN_RxData[3]);
		// convert to rad/s
		speed_data[motor_idx] = (rpm / REDUCTION_RATIO) * RPM_TO_RADS;

		// torque current of the motor
		torque_current_data[motor_idx] = (CAN_RxData[4] << 8 | CAN_RxData[5]);
	}
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	if (huart != &huart4) {
		return;
	}

	switch (uart_state) {
	case UART_STATE_WAIT_HEADER_1:
		if (rx_byte == active_header_byte_1) {
			expected_header_byte_2 = active_header_byte_2;
			header_candidate_is_legacy = false;
			uart_state = UART_STATE_WAIT_HEADER_2;
		} else if (legacy_accept_enabled && (rx_byte == legacy_header_byte_1)) {
			expected_header_byte_2 = legacy_header_byte_2;
			header_candidate_is_legacy = true;
			uart_state = UART_STATE_WAIT_HEADER_2;
		}
		HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
		break;
	case UART_STATE_WAIT_HEADER_2:
		if (is_header_match(rx_byte, expected_header_byte_2)) {
			uart_state = UART_STATE_WAIT_TYPE;
		} else if (rx_byte == active_header_byte_1 || (legacy_accept_enabled && rx_byte == legacy_header_byte_1)) {
			expected_header_byte_2 = (rx_byte == active_header_byte_1) ? active_header_byte_2 : legacy_header_byte_2;
			header_candidate_is_legacy = (rx_byte == legacy_header_byte_1);
			uart_state = UART_STATE_WAIT_HEADER_2;
		} else {
			uart_state = UART_STATE_WAIT_HEADER_1;
		}
		HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
		break;
	case UART_STATE_WAIT_TYPE:
		current_frame_type = rx_byte;
		switch (current_frame_type) {
		case FRAME_TYPE_DRIVE_COMMAND:
			expected_payload_length = UART_DRIVE_PAYLOAD_SIZE;
			break;
		case FRAME_TYPE_PID_UPDATE:
			expected_payload_length = UART_PID_PAYLOAD_SIZE;
			break;
		case FRAME_TYPE_HEADER_CONFIG:
			expected_payload_length = UART_CONFIG_PAYLOAD_SIZE;
			break;
		default:
			expected_payload_length = 0;
			break;
		}
		if (expected_payload_length > 0) {
			uart_state = UART_STATE_WAIT_PAYLOAD;
			HAL_UART_Receive_IT(&huart4, uart_rx_buffer, expected_payload_length);
		} else {
			reset_uart_state_machine();
		}
		break;
	case UART_STATE_WAIT_PAYLOAD:
		if (current_frame_type == FRAME_TYPE_DRIVE_COMMAND) {
			handle_drive_payload();
		} else if (current_frame_type == FRAME_TYPE_PID_UPDATE) {
			handle_pid_payload();
		} else if (current_frame_type == FRAME_TYPE_HEADER_CONFIG) {
			handle_header_config_payload();
		}
		reset_uart_state_machine();
		break;
	default:
		reset_uart_state_machine();
		break;
	}
}

