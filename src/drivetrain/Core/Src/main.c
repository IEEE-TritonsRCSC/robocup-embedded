/* USER CODE BEGIN 4 */
void setMotorSpeeds(int16_t ms1, int16_t ms2, int16_t ms3, int16_t ms4, int16_t msg5) {
	uint8_t h1 = ms1 >> 8;
	uint8_t l1 = ms1;
	uint8_t h2 = ms2 >> 8;
	uint8_t l2 = ms2;
	uint8_t h3 = ms3 >> 8;
	uint8_t l3 = ms3;
	uint8_t h4 = ms4 >> 8;
	uint8_t l4 = ms4;
	uint8_t h5 = msg5 >> 8;
	uint8_t l5 = msg5;
	runMotors(h1, l1, h2, l2, h3, l3, h4, l4, h5, l5);
}

void runMotors(unsigned char motorOneHigh, unsigned char motorOneLow,
		unsigned char motorTwoHigh, unsigned char motorTwoLow,
		unsigned char motorThreeHigh, unsigned char motorThreeLow,
		unsigned char motorFourHigh, unsigned char motorFourLow,
		unsigned char motorFiveHigh, unsigned char motorFiveLow) {

	//speed can be 16 bits, split into high and low bytes
	CAN_TxData[0] = motorOneHigh;      //high byte for speed, shifted 8 because only buffer is only 8 bits
	CAN_TxData[1] = motorOneLow;       //low bytes for speed
	CAN_TxData[2] = motorTwoHigh;
	CAN_TxData[3] = motorTwoLow;
	CAN_TxData[4] = motorThreeHigh;
	CAN_TxData[5] = motorThreeLow;
	CAN_TxData[6] = motorFourHigh;
	CAN_TxData[7] = motorFourLow;

	CAN2_TxData[0] = motorFiveHigh;
	CAN2_TxData[1] = motorFiveLow;

	HAL_CAN_AddTxMessage(&hcan1, &canTxHeader, CAN_TxData, &canTxMailbox);
	HAL_CAN_AddTxMessage(&hcan1, &canTxHeader2, CAN2_TxData, &canTxMailbox);
}

static void handle_drive_payload(void) {
	timeout = 0;
	for (int i = 0; i < 4; ++i) {
		const int index = i * 2;
		int16_t raw_value = (int16_t) ((uart_rx_buffer[index] << 8) | uart_rx_buffer[index + 1]);
		targetSpeeds[i] = raw_value;
	}
	dribble_speed = (int8_t) uart_rx_buffer[8];
	memset(uart_rx_buffer, 0, UART_RX_BUFFER_SIZE);
	HAL_GPIO_TogglePin(LED_GREEN_PORT, LED_GREEN_PIN);
}

static void apply_pid_constants_for_wheel(uint8_t wheel, float kp, float ki, float kd) {
	pid_set_constants(&motor_pid[wheel], kp, ki, kd);
	motor_pid[wheel].integral = 0.0f;
	motor_pid[wheel].error = 0.0f;
	motor_pid[wheel].last_error = 0.0f;
	motor_pid[wheel].output = 0.0f;
	switch (wheel) {
	case 0:
		Kp1 = kp;
		Ki1 = ki;
		Kd1 = kd;
		break;
	case 1:
		Kp2 = kp;
		Ki2 = ki;
		Kd2 = kd;
		break;
	case 2:
		Kp3 = kp;
		Ki3 = ki;
		Kd3 = kd;
		break;
	case 3:
		Kp4 = kp;
		Ki4 = ki;
		Kd4 = kd;
		break;
	default:
		break;
	}
}

static void handle_pid_payload(void) {
	if (expected_payload_length != UART_PID_PAYLOAD_SIZE) {
		return;
	}
	uint8_t wheel = uart_rx_buffer[0];
	float kp = bytes_to_float_be(&uart_rx_buffer[1]);
	float ki = bytes_to_float_be(&uart_rx_buffer[5]);
	float kd = bytes_to_float_be(&uart_rx_buffer[9]);
	if (wheel < 4) {
		apply_pid_constants_for_wheel(wheel, kp, ki, kd);
	} else if (wheel == 0xFF) {
		for (uint8_t i = 0; i < 4; ++i) {
			apply_pid_constants_for_wheel(i, kp, ki, kd);
		}
	}
}

static void handle_header_config_payload(void) {
	if (expected_payload_length != UART_CONFIG_PAYLOAD_SIZE) {
		return;
	}
	uint8_t new_header_1 = uart_rx_buffer[0];
	uint8_t new_header_2 = uart_rx_buffer[1];
	uint8_t checksum = uart_rx_buffer[2];
	uint8_t expected_checksum = HEADER_CHECKSUM_SEED ^ new_header_1 ^ new_header_2;
	if (checksum != expected_checksum) {
		return;
	}
	uint8_t prev_header_1 = active_header_byte_1;
	uint8_t prev_header_2 = active_header_byte_2;
	active_header_byte_1 = new_header_1;
	active_header_byte_2 = new_header_2;
	legacy_header_byte_1 = prev_header_1;
	legacy_header_byte_2 = prev_header_2;
	legacy_accept_enabled = true;
	legacy_accept_deadline = HAL_GetTick() + HEADER_LEGACY_GRACE_MS;
	persist_header_state(active_header_byte_1, active_header_byte_2,
		legacy_header_byte_1, legacy_header_byte_2, legacy_accept_enabled);
}

static void reset_uart_state_machine(void) {
	uart_state = UART_STATE_WAIT_HEADER_1;
	current_frame_type = 0;
	expected_payload_length = 0;
	expected_header_byte_2 = active_header_byte_2;
	header_candidate_is_legacy = false;
	HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
}

static float bytes_to_float_be(const uint8_t *bytes) {
	uint32_t value = ((uint32_t) bytes[0] << 24) |
			((uint32_t) bytes[1] << 16) |
			((uint32_t) bytes[2] << 8) |
			((uint32_t) bytes[3]);
	float result;
	memcpy(&result, &value, sizeof(float));
	return result;
}

static void send_telemetry_if_due(void) {
	uint32_t now = HAL_GetTick();
	if ((now - last_telemetry_ms) < TELEMETRY_INTERVAL_MS) {
		return;
	}
	last_telemetry_ms = now;
	compose_telemetry_frame();
	HAL_UART_Transmit(&huart4, telemetry_buffer, TELEMETRY_FRAME_SIZE, HAL_MAX_DELAY);
}

static int16_t clamp_to_int16(float value) {
	if (value > INT16_MAX) {
		return INT16_MAX;
	}
	if (value < INT16_MIN) {
		return INT16_MIN;
	}
	return (int16_t) value;
}

static bool is_header_match(uint8_t candidate, uint8_t expected) {
	return candidate == expected;
}

static void ensure_backup_domain_access(void) {
	__HAL_RCC_PWR_CLK_ENABLE();
	HAL_PWR_EnableBkUpAccess();
	__HAL_RCC_BKPSRAM_CLK_ENABLE();
}

static void load_persisted_header(void) {
	ensure_backup_domain_access();
	const HeaderStorageRecord *stored = HEADER_STORAGE_PTR;
	uint32_t active_pair = pack_header_pair(DEFAULT_HEADER_BYTE_1,
			DEFAULT_HEADER_BYTE_2);
	uint32_t legacy_pair = pack_header_pair(LEGACY_HEADER_BYTE_1,
			LEGACY_HEADER_BYTE_2);
	uint32_t legacy_flag = 0;
	bool valid = false;
	uint32_t expected_checksum = calculate_storage_checksum(HEADER_PERSIST_MAGIC,
			HEADER_STORAGE_VERSION, stored->active_pair, stored->legacy_pair,
			stored->legacy_enabled);
	if ((stored->magic == HEADER_PERSIST_MAGIC)
			&& (stored->version == HEADER_STORAGE_VERSION)
			&& (stored->checksum == expected_checksum)) {
		active_pair = stored->active_pair;
		legacy_pair = stored->legacy_pair;
		legacy_flag = stored->legacy_enabled;
		valid = true;
	}
	uint8_t active_h1;
	uint8_t active_h2;
	uint8_t legacy_h1;
	uint8_t legacy_h2;
	unpack_header_pair(active_pair, &active_h1, &active_h2);
	unpack_header_pair(legacy_pair, &legacy_h1, &legacy_h2);
	active_header_byte_1 = active_h1;
	active_header_byte_2 = active_h2;
	legacy_header_byte_1 = legacy_h1;
	legacy_header_byte_2 = legacy_h2;
	legacy_accept_enabled = (legacy_flag != 0u);
	if (!valid) {
		persist_header_state(active_header_byte_1, active_header_byte_2,
			legacy_header_byte_1, legacy_header_byte_2, legacy_accept_enabled);
	}
	if (legacy_accept_enabled) {
		legacy_accept_deadline = HAL_GetTick() + HEADER_LEGACY_GRACE_MS;
	} else {
		legacy_accept_deadline = 0;
	}
}

static uint32_t pack_header_pair(uint8_t h1, uint8_t h2) {
	return ((uint32_t) h1 << 8) | h2;
}

static void unpack_header_pair(uint32_t pair, uint8_t *h1, uint8_t *h2) {
	*h1 = (pair >> 8) & 0xFF;
	*h2 = pair & 0xFF;
}

static uint32_t calculate_storage_checksum(uint32_t magic, uint32_t version,
		uint32_t active_pair, uint32_t legacy_pair, uint32_t legacy_enabled) {
	uint32_t checksum = HEADER_CHECKSUM_SEED;
	checksum ^= magic;
	checksum ^= version;
	checksum ^= active_pair;
	checksum ^= legacy_pair;
	checksum ^= legacy_enabled;
	return checksum;
}

static void persist_header_state(uint8_t active_h1, uint8_t active_h2,
		uint8_t legacy_h1, uint8_t legacy_h2, bool legacy_enabled) {
	ensure_backup_domain_access();
	HeaderStorageRecord record;
	record.magic = HEADER_PERSIST_MAGIC;
	record.version = HEADER_STORAGE_VERSION;
	record.active_pair = pack_header_pair(active_h1, active_h2);
	record.legacy_pair = pack_header_pair(legacy_h1, legacy_h2);
	record.legacy_enabled = legacy_enabled ? 1u : 0u;
	record.checksum = calculate_storage_checksum(record.magic,
			record.version, record.active_pair, record.legacy_pair,
			record.legacy_enabled);
	memcpy((void *) HEADER_STORAGE_PTR, &record, sizeof(record));
}

static void maybe_disable_legacy_window(void) {
	if (!legacy_accept_enabled) {
		return;
	}
	uint32_t now = HAL_GetTick();
	if ((int32_t) (now - legacy_accept_deadline) >= 0) {
		legacy_accept_enabled = false;
		legacy_accept_deadline = 0;
		persist_header_state(active_header_byte_1, active_header_byte_2,
			legacy_header_byte_1, legacy_header_byte_2, legacy_accept_enabled);
	}
}

static void compose_telemetry_frame(void) {
	telemetry_buffer[0] = TELEMETRY_HEADER_BYTE_1;
	telemetry_buffer[1] = TELEMETRY_HEADER_BYTE_2;
	uint32_t timestamp = HAL_GetTick();
	telemetry_buffer[2] = (timestamp >> 24) & 0xFF;
	telemetry_buffer[3] = (timestamp >> 16) & 0xFF;
	telemetry_buffer[4] = (timestamp >> 8) & 0xFF;
	telemetry_buffer[5] = (timestamp & 0xFF);
	for (int i = 0; i < TELEMETRY_WHEEL_COUNT; ++i) {
		int base = 6 + (i * TELEMETRY_WHEEL_STRIDE);
		int16_t target = clamp_to_int16(targetSpeeds[i]);
		int16_t actual = clamp_to_int16(speed_data[i] * 100.0f);
		int16_t output = clamp_to_int16(motor_pid[i].output);
		telemetry_buffer[base] = (target >> 8) & 0xFF;
		telemetry_buffer[base + 1] = target & 0xFF;
		telemetry_buffer[base + 2] = (actual >> 8) & 0xFF;
		telemetry_buffer[base + 3] = actual & 0xFF;
		telemetry_buffer[base + 4] = (output >> 8) & 0xFF;
		telemetry_buffer[base + 5] = output & 0xFF;
	}
	int16_t dribble_word = clamp_to_int16(dribble_speed * 100.0f);
	int tail = 6 + (TELEMETRY_WHEEL_COUNT * TELEMETRY_WHEEL_STRIDE);
	telemetry_buffer[tail] = (dribble_word >> 8) & 0xFF;
	telemetry_buffer[tail + 1] = dribble_word & 0xFF;
}

