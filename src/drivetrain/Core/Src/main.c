void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan) {
	//HAL_GPIO_TogglePin(LED_GREEN_PORT,LED_GREEN_PIN);
	if (hcan != &hcan1) {
		return;
	}

	// Read the incoming CAN message.
	if (HAL_CAN_GetRxMessage(&hcan1, CAN_RX_FIFO0, &canRxHeader, CAN_RxData) != HAL_OK) {
		return;
	}

	// Map StdId to motor index and update feedback buffers.
	uint8_t index = 0;
	if (!motor_index_from_std_id(canRxHeader.StdId, &index)) {
		return;
	}

	motor_idx = index;
	update_feedback_from_can(index, CAN_RxData);
}


void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	(void)huart;
	// Called when a byte or the full UART payload has been received.

	if (!header1_flag) {
		if (rx_byte == HEADER_BYTE_1) {
			// First header byte received.
			header1_flag = 1;
		}
		HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
		return;
	}

	if (header2_flag) {
		// Full message received.
		timeout = 0;

		if (rx_mode == UART_RX_MODE_RUNTIME) {
			apply_uart_packet(uart_rx_buffer);
		} else if (rx_mode == UART_RX_MODE_PID) {
			apply_pid_packet(uart_rx_buffer);
		}
		clear_buffer(uart_rx_buffer, UART_RX_BUFFER_SIZE);
		HAL_GPIO_TogglePin(LED_GREEN_PORT, LED_GREEN_PIN);

		header1_flag = 0;
		header2_flag = 0;
		rx_mode = UART_RX_MODE_NONE;
		rx_expected_length = 0;
		HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
		return;
	}

	if (rx_byte == HEADER_BYTE_2_RUNTIME) {
		// Second header byte received; read full payload.
		header2_flag = 1;
		rx_mode = UART_RX_MODE_RUNTIME;
		rx_expected_length = UART_RX_PAYLOAD_RUNTIME;
		HAL_UART_Receive_IT(&huart4, uart_rx_buffer, rx_expected_length);
		return;
	}

	if (rx_byte == HEADER_BYTE_2_PID) {
		// PID tuning packet received; read tuning payload.
		header2_flag = 1;
		rx_mode = UART_RX_MODE_PID;
		rx_expected_length = UART_RX_PAYLOAD_PID;
		HAL_UART_Receive_IT(&huart4, uart_rx_buffer, rx_expected_length);
		return;
	}

	// Header mismatch; reset and look for the first header byte again.
	header1_flag = 0;
	HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
}

void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart) {
	if (huart == &huart4) {
		telemetry_tx_busy = 0;
	}
}


/**
 * @brief System Clock Configuration
 * @retval None
 */
