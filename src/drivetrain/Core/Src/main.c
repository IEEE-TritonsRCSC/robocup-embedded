// Convert CAN StdId into motor index (0..MOTOR_COUNT-1).
static uint8_t motor_index_from_std_id(uint32_t std_id, uint8_t *out_index)
{
	if (std_id < CAN_MOTOR_RX_STDID_BASE
			|| std_id >= (CAN_MOTOR_RX_STDID_BASE + MOTOR_COUNT)) {
		return 0;
	}
	*out_index = (uint8_t)(std_id - CAN_MOTOR_RX_STDID_BASE);
	return 1;
}

// Update feedback arrays from a CAN RX payload.
static void update_feedback_from_can(uint8_t index, const uint8_t data[8])
{
	if (index >= MOTOR_COUNT) {
		return;
	}

	// Angle of the motor (0 - 8191 corresponding with 0 - 360 degrees).
	angle_data[index] = (uint16_t) (data[0] << 8 | data[1]);

	// Speed of the motor in rpm, converted to rad/s after gear reduction.
	int16_t rpm = (int16_t)((data[2] << 8) | data[3]);
	speed_data[index] = (rpm / REDUCTION_RATIO) * RPM_TO_RADS;

	// Torque current of the motor (raw units).
	torque_current_data[index] = (float)((data[4] << 8) | data[5]);
}

// Apply a full UART payload (already stripped of header bytes).
static void apply_uart_packet(const uint8_t *payload)
{
	targetSpeeds[0] = (float)bytes_to_int16_be(&payload[0]);
	targetSpeeds[1] = (float)bytes_to_int16_be(&payload[2]);
	targetSpeeds[2] = (float)bytes_to_int16_be(&payload[4]);
	targetSpeeds[3] = (float)bytes_to_int16_be(&payload[6]);
	// Optional tuning: boost front-right wheel (disabled by default).
	// targetSpeeds[0] = targetSpeeds[0] * 1.15f;
	// Historical note: |targetSpeeds[i]| was previously limited to 500.
	dribble_speed = (int8_t)payload[8];
}

// Update PID gains from a tuning packet payload.
static void apply_pid_packet(const uint8_t *payload)
{
	uint8_t wheel = payload[0];
	int16_t kp_q = bytes_to_int16_be(&payload[1]);
	int16_t ki_q = bytes_to_int16_be(&payload[3]);
	int16_t kd_q = bytes_to_int16_be(&payload[5]);

	float kp = ((float)kp_q) / PID_SCALE;
	float ki = ((float)ki_q) / PID_SCALE;
	float kd = ((float)kd_q) / PID_SCALE;

	if (wheel == PID_WHEEL_ALL || wheel == PID_WHEEL_ALL_ALT) {
		for (uint8_t i = 0; i < MOTOR_COUNT; ++i) {
			set_pid_for_wheel(i, kp, ki, kd);
		}
		return;
	}

	set_pid_for_wheel(wheel, kp, ki, kd);
}

// One iteration of the main control loop.
static void control_loop_step(void)
{
	float dt_ms = ramp_get_dt_ms();
	
	// Safety timeout when UART disconnects (uncomment if needed).
	if (timeout >= 200) {
		for (int i = 0; i < MOTOR_COUNT; ++i) {
			targetSpeeds[i] = 0.0f;
		}
	}
	

	for (int i = 0; i < MOTOR_COUNT; ++i) {
		// Target speeds arrive in centi-units; scale to match feedback units.
		float target = ((float)targetSpeeds[i]) / TARGET_SCALE;
		// Ramp the target to avoid instant changes.
		ramped_target_speeds[i] = ramp_linear(ramped_target_speeds[i], target,
				WHEEL_RAMP_MS_PER_UNIT, dt_ms);
		motor_pid[i].target = ramped_target_speeds[i];
		pid_calculate(&motor_pid[i], speed_data[i]);
	}

	// Ramp the dribbler command as well.
	float dribbler_target = (float)dribble_speed * DRIBBLE_SCALE;
	ramped_dribbler_speed = ramp_linear(ramped_dribbler_speed, dribbler_target,
			DRIBBLER_RAMP_MS_PER_UNIT, dt_ms);

	setMotorSpeeds((int16_t)motor_pid[0].output,
			(int16_t)motor_pid[1].output,
			(int16_t)motor_pid[2].output,
			(int16_t)motor_pid[3].output,
			(int16_t)ramped_dribbler_speed);

	timeout++;
}

// Send telemetry at a fixed rate without blocking the control loop.
static void telemetry_try_send(void)
{
#if TELEMETRY_ENABLED
	if (telemetry_tx_busy) {
		return;
	}

	uint32_t now = HAL_GetTick();
	if ((now - telemetry_last_ms) < TELEMETRY_PERIOD_MS) {
		return;
	}

	telemetry_tx_buffer[0] = TELEMETRY_HEADER_1;
	telemetry_tx_buffer[1] = TELEMETRY_HEADER_2;
	telemetry_tx_buffer[2] = (uint8_t)((now >> 24) & 0xFF);
	telemetry_tx_buffer[3] = (uint8_t)((now >> 16) & 0xFF);
	telemetry_tx_buffer[4] = (uint8_t)((now >> 8) & 0xFF);
	telemetry_tx_buffer[5] = (uint8_t)(now & 0xFF);

	uint8_t *payload = &telemetry_tx_buffer[6];
	for (int i = 0; i < MOTOR_COUNT; ++i) {
		int16_t target = clamp_int16_from_float(motor_pid[i].target * TARGET_SCALE);
		int16_t actual = clamp_int16_from_float(speed_data[i] * TARGET_SCALE);
		int16_t output = clamp_int16_from_float(motor_pid[i].output);

		split_int16(target, &payload[0], &payload[1]);
		split_int16(actual, &payload[2], &payload[3]);
		split_int16(output, &payload[4], &payload[5]);
		payload += 6;
	}

	if (HAL_UART_Transmit_IT(&huart4, telemetry_tx_buffer, TELEMETRY_PACKET_SIZE) == HAL_OK) {
		telemetry_tx_busy = 1;
		telemetry_last_ms = now;
	}
#endif
}

// Update PID gains for a single wheel and keep shadow variables in sync.
static void set_pid_for_wheel(uint8_t wheel, float kp, float ki, float kd)
{
	if (wheel >= MOTOR_COUNT) {
		return;
	}

	switch (wheel) {
	case 0:
		Kp1 = kp;
		Ki1 = ki;
		Kd1 = kd;
		break;
	case 1:
		Kp2 = kp;
		Ki2 = ki;
		Kd2 = kd;
		break;
	case 2:
		Kp3 = kp;
		Ki3 = ki;
		Kd3 = kd;
		break;
	case 3:
		Kp4 = kp;
		Ki4 = ki;
		Kd4 = kd;
		break;
	default:
		return;
	}

	pid_set_constants(&motor_pid[wheel], kp, ki, kd);
}

