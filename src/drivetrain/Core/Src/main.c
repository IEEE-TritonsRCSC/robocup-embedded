// Clear a buffer to zero.
static void clear_buffer(uint8_t *buffer, uint32_t length)
{
	for (uint32_t i = 0; i < length; ++i) {
		buffer[i] = 0;
	}
}

// Split a signed 16-bit value into high/low bytes (big-endian).
static void split_int16(int16_t value, uint8_t *high, uint8_t *low)
{
	uint16_t uvalue = (uint16_t)value;
	*high = (uint8_t)((uvalue >> 8) & 0xFF);
	*low = (uint8_t)(uvalue & 0xFF);
}

// Combine two bytes into a signed 16-bit value (big-endian).
static int16_t bytes_to_int16_be(const uint8_t *bytes)
{
	return (int16_t)((bytes[0] << 8) | bytes[1]);
}

// Clamp and round a float into int16 range.
static int16_t clamp_int16_from_float(float value)
{
	if (value > (float)INT16_MAX) {
		return INT16_MAX;
	}
	if (value < (float)INT16_MIN) {
		return INT16_MIN;
	}
	if (value >= 0.0f) {
		value += 0.5f;
	} else {
		value -= 0.5f;
	}
	return (int16_t)value;
}

// Linear ramp limiter: advances current toward target at a fixed slope.
// ms_per_unit sets how many milliseconds it takes to change by 1 unit.
static float ramp_linear(float current, float target, float ms_per_unit, float dt_ms)
{
	if (ms_per_unit <= 0.0f) {
		return target;
	}

	if (dt_ms <= 0.0f) {
		return current;
	}

	float max_delta = dt_ms / ms_per_unit;
	float delta = target - current;

	if (delta > max_delta) {
		delta = max_delta;
	} else if (delta < -max_delta) {
		delta = -max_delta;
	}

	return current + delta;
}

// Compute elapsed time since last ramp update in milliseconds.
static float ramp_get_dt_ms(void)
{
	uint32_t now = HAL_GetTick();
	if (ramp_last_ms == 0) {
		ramp_last_ms = now;
		return 0.0f;
	}

	uint32_t dt_ms = now - ramp_last_ms;
	ramp_last_ms = now;
	return (float)dt_ms;
}

