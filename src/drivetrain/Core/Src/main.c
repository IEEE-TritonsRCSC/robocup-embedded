void setMotorSpeeds(int16_t ms1, int16_t ms2, int16_t ms3, int16_t ms4, int16_t msg5) {
	uint8_t h1 = 0, l1 = 0;
	uint8_t h2 = 0, l2 = 0;
	uint8_t h3 = 0, l3 = 0;
	uint8_t h4 = 0, l4 = 0;
	uint8_t h5 = 0, l5 = 0;

	// Split each command into high/low bytes for CAN.
	split_int16(ms1, &h1, &l1);
	split_int16(ms2, &h2, &l2);
	split_int16(ms3, &h3, &l3);
	split_int16(ms4, &h4, &l4);
	split_int16(msg5, &h5, &l5);

	runMotors(h1, l1, h2, l2, h3, l3, h4, l4, h5, l5);
}

void runMotors(uint8_t motorOneHigh, uint8_t motorOneLow,
		uint8_t motorTwoHigh, uint8_t motorTwoLow,
		uint8_t motorThreeHigh, uint8_t motorThreeLow,
		uint8_t motorFourHigh, uint8_t motorFourLow,
		uint8_t motorFiveHigh, uint8_t motorFiveLow) {

	// Speed commands are 16-bit values split into high/low bytes.
	CAN_TxData[0] = motorOneHigh;
	CAN_TxData[1] = motorOneLow;
	CAN_TxData[2] = motorTwoHigh;
	CAN_TxData[3] = motorTwoLow;
	CAN_TxData[4] = motorThreeHigh;
	CAN_TxData[5] = motorThreeLow;
	CAN_TxData[6] = motorFourHigh;
	CAN_TxData[7] = motorFourLow;

	CAN2_TxData[0] = motorFiveHigh;
	CAN2_TxData[1] = motorFiveLow;
	for (int i = 2; i < 8; ++i) {
		CAN2_TxData[i] = 0;
	}

	HAL_CAN_AddTxMessage(&hcan1, &canTxHeader, CAN_TxData, &canTxMailbox);
	HAL_CAN_AddTxMessage(&hcan1, &canTxHeader2, CAN2_TxData, &canTxMailbox);
}

